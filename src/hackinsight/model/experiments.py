"""Optimization log, measured (never typed by hand).

Each experiment changes ONE thing and records accuracy (validation MAE - the test set is not used
to make decisions), run time and memory, then says whether the change was kept.
Writes artifacts/optimization_log.json and docs/optimization_log.md.

    python -m hackinsight.model.experiments
"""
from __future__ import annotations

import json
import shutil
import tempfile
import time
from pathlib import Path

import psutil

from .. import config
from . import train


def _model(gold, **kw):
    t = time.perf_counter()
    r = train.run_one(gold, config.PRIMARY_DISEASE, save=False, **kw)
    return {"val_mae": round(r["validation"]["mae_model"], 2), "val_mae_baseline": round(r["validation"]["mae_baseline"], 2),
            "seconds": round(time.perf_counter() - t, 1), "rss_mb_delta": r["peak_rss_mb_delta"],
            "n_features": len(r["features"])}


def exp_parse_parallel(n: int = 12) -> dict:
    """PDF parsing: 1 worker vs several workers, on the same n bulletins, cold cache."""
    from concurrent.futures import ProcessPoolExecutor
    from ..manifest import Manifest
    from ..warehouse.extract import NAME_RE, _parse_one
    man = Manifest()
    todo = []
    for e in man.entries("nih_idsr"):
        m = NAME_RE.search(e.path)
        if m:
            todo.append((str(config.ROOT / e.path), e.sha256, int(m.group(1)), int(m.group(2))))
    todo = todo[-n:]
    t = time.perf_counter()
    rows1 = sum(len(_parse_one(a)[0]) for a in todo)
    seq = time.perf_counter() - t
    workers = max(1, min(8, (psutil.cpu_count() or 2) - 1))
    t = time.perf_counter()
    with ProcessPoolExecutor(max_workers=workers) as ex:
        rows2 = sum(len(r[0]) for r in ex.map(_parse_one, todo))
    par = time.perf_counter() - t
    return {"bulletins": len(todo), "seq_seconds": round(seq, 1), "parallel_seconds": round(par, 1),
            "workers": workers, "same_rows": rows1 == rows2, "rows": rows1}


def exp_embedding_cache() -> dict:
    from ..rag import index
    cache = index.RAG_DIR / "emb_cache.npz"
    backup = None
    if cache.exists():
        backup = Path(tempfile.mkdtemp()) / "emb_cache.npz"
        shutil.copy2(cache, backup)
        cache.unlink()
    t = time.perf_counter()
    n = index.build()
    cold = time.perf_counter() - t
    t = time.perf_counter()
    index.build()
    warm = time.perf_counter() - t
    return {"chunks": n, "cold_seconds": round(cold, 1), "warm_seconds": round(warm, 1)}


def run() -> list[dict]:
    gold = train.load_gold()
    log = []
    full = _model(gold)
    again = _model(gold)          # reliability: the same seed must give the same validation MAE
    no_w = _model(gold, use_weather=False)
    log.append({"change": "Add weather features (rain, humidity, temperature, lags 0-3 weeks)",
                "before": no_w, "after": full,
                "kept": full["val_mae"] <= no_w["val_mae"],
                "note": "kept if validation MAE does not get worse"})
    small = _model(gold, grid=[train.PARAM_GRID[0]])
    log.append({"change": "Tuning grid: 6 settings -> 1 setting (num_leaves=7)", "before": full, "after": small,
                "kept": small["val_mae"] <= full["val_mae"] * 1.01,
                "note": "kept only if accuracy within 1% while saving time"})
    st = json.loads((config.ARTIFACTS / "status.json").read_text(encoding="utf-8"))
    log.append({"change": "PDF parsing: process pool instead of one process", "result": exp_parse_parallel(),
                "kept": True, "note": "identical rows, faster wall-clock"})
    log.append({"change": "Cache parsed PDFs by SHA-256 + skip past-year weather files with a valid hash (incremental run)",
                "result": {"last_run_mode": st["last_run"]["mode"], "last_run_seconds": st["last_run"].get("duration_s"),
                           "steps": {k: v.get("seconds") for k, v in st["last_run"]["steps"].items() if isinstance(v, dict)}},
                "kept": True, "note": "compare a `make data` (full) run with a `make update` (incremental) run"})
    log.append({"change": "Cache sentence embeddings by chunk hash", "result": exp_embedding_cache(), "kept": True,
                "note": "re-index after a new bulletin only embeds new chunks"})
    reliability = {"seed": config.SEED, "val_mae_run1": full["val_mae"], "val_mae_run2": again["val_mae"],
                   "same_result": full["val_mae"] == again["val_mae"],
                   "same_time_split": f"validation from {config.VAL_START}, test from {config.TEST_START}"}
    (config.ARTIFACTS / "optimization_log.json").write_text(
        json.dumps({"changes": log, "reliability": reliability}, indent=2), encoding="utf-8")
    _write_md(log, reliability)
    return log


def _write_md(log: list[dict], reliability: dict) -> None:
    lines = ["# Optimization log (generated by `python -m hackinsight.model.experiments`)", "",
             "Decisions use the validation period only; the test set is scored once in `make train`.", ""]
    for i, e in enumerate(log, 1):
        lines.append(f"## Change {i}: {e['change']}")
        if "before" in e:
            b, a = e["before"], e["after"]
            lines += ["| | val MAE | seconds | memory delta MB | features |", "|---|---|---|---|---|",
                      f"| before | {b['val_mae']} | {b['seconds']} | {b['rss_mb_delta']} | {b['n_features']} |",
                      f"| after | {a['val_mae']} | {a['seconds']} | {a['rss_mb_delta']} | {a['n_features']} |",
                      f"| baseline | {b['val_mae_baseline']} | | | |"]
        else:
            lines.append("```json\n" + json.dumps(e["result"], indent=2) + "\n```")
        lines += [f"**Kept:** {'yes' if e['kept'] else 'no'} - {e['note']}", ""]
    r = reliability
    lines += ["## Reliability checks",
              f"- Same seed ({r['seed']}) trained twice: validation MAE {r['val_mae_run1']} and {r['val_mae_run2']} "
              f"({'identical' if r['same_result'] else 'NOT identical'}).",
              f"- Every change above is compared on the same time-based split ({r['same_time_split']}); "
              "decisions use validation only.",
              "- Errors by group for the served model are in `artifacts/model_*/metrics.json` and the model card.", ""]
    w, g = log[0], log[1]
    lines += ["## Trade-off in two sentences",
              f"Weather features cost {w['after']['seconds'] - w['before']['seconds']:.1f} s more training and "
              f"{w['after']['rss_mb_delta'] - w['before']['rss_mb_delta']:+.0f} MB of memory for a validation MAE of "
              f"{w['after']['val_mae']} instead of {w['before']['val_mae']}, so we "
              f"{'kept' if w['kept'] else 'dropped'} them. A smaller tuning grid would save "
              f"{g['before']['seconds'] - g['after']['seconds']:.1f} s but moves validation MAE to {g['after']['val_mae']}, "
              f"so we {'took' if g['kept'] else 'rejected'} it: accuracy for the officer matters more than seconds "
              "in an hourly job.", ""]
    (config.ROOT / "docs" / "optimization_log.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    for e in run():
        print(e["change"], "->", "kept" if e["kept"] else "rejected")
